-- =====================================================================================
-- 升级脚本（存量库执行）：知识评测「平均耗时」改口径为「总耗时」（列改名）
-- 对应 v2_init.sql 里 tb_rag_eval_run 的 total_latency_ms 列（新装库无需执行本脚本）。
--
-- 背景：原 avg_latency_ms 是「平均逐对延迟（召回+生成，不含打分）」，信息量弱且
-- 看不出一场评测整体跑了多久。改为 total_latency_ms = worker 从队列取到任务起、
-- 到 run 收口的墙钟差（含整段执行：并发召回+生成、RAGAS 打分、回填落库）。
--
-- 注意：CHANGE COLUMN 会保留存量行的数值，但存量值仍是旧口径（平均逐对延迟，
-- 量级约为新口径的 1/N 且不含打分段），仅作占位；新发起或「重新执行」过的评测
-- 才会落新口径数值。
--
-- 执行方式（MySQL 客户端连上目标库后执行本文件）：
--   重复执行会报 Unknown column 'avg_latency_ms'（已改名），忽略即可。
-- =====================================================================================

ALTER TABLE `tb_rag_eval_run`
    CHANGE COLUMN `avg_latency_ms` `total_latency_ms` INT NOT NULL DEFAULT 0
        COMMENT '总耗时（worker 取到任务到收口的墙钟差，含召回+生成+打分）';
